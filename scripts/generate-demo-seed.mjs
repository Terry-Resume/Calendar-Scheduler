#!/usr/bin/env node
// Generates supabase/seed.demo.sql from the shared fictional studio in @kato8/core,
// so the Scheduler's demo data matches the roster in HR, EA and the hub.
//   npm run seed:demo   →   supabase/seed.demo.sql   (run it in the Supabase SQL editor)
import { writeFileSync } from 'node:fs'
import { TEAM, STUDIO } from '@kato8/core'

const q = v => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)
const uid = id => `demo_${id}`
const arr = list => `ARRAY[${list.map(q).join(',')}]::text[]`
const uuid = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`

const byTeam = team => TEAM.filter(m => m.team === team || m.team === 'studio')
const lead = team => TEAM.find(m => m.team === team && /lead/i.test(m.role)) ?? TEAM[0]

const projects = [
  { n: 1, name: 'Last Light', game: 'last-light', color: '#0d9488', type: 'kanban', desc: 'Atmospheric narrative puzzle game' },
  { n: 2, name: 'Corebound', game: 'corebound', color: '#2563eb', type: 'kanban', desc: 'Action-RPG with procedural dungeon systems' },
  { n: 3, name: 'Big Boss Cleanup', game: 'big-boss-cleanup', color: '#d97706', type: 'art_pipeline', desc: 'Comedy cleanup sim, art pipeline board' },
]

const out = []
out.push(`-- Demo seed for ${STUDIO.name} (fictional). Generated by scripts/generate-demo-seed.mjs — do not edit by hand.`)
out.push('-- Safe to re-run: rows use fixed ids and ON CONFLICT DO NOTHING / DO UPDATE.')
out.push('BEGIN;')

out.push('-- People')
for (const m of TEAM) {
  out.push(`INSERT INTO profiles (user_id, display_name, role, team, teams) VALUES (${q(uid(m.id))}, ${q(m.name)}, ${q(m.role)}, ${q(m.team)}, ${arr([m.team])}) ON CONFLICT (user_id) DO UPDATE SET display_name = EXCLUDED.display_name, role = EXCLUDED.role, team = EXCLUDED.team;`)
}

out.push('-- Projects, sprints, milestones')
for (const p of projects) {
  const members = byTeam(p.game).map(m => uid(m.id))
  out.push(`INSERT INTO projects (id, name, description, game, team, type, color, owner_id, member_ids) VALUES (${q(uuid(p.n))}, ${q(p.name)}, ${q(p.desc)}, ${q(p.game)}, ${q(p.game)}, ${q(p.type)}, ${q(p.color)}, ${q(uid(lead(p.game).id))}, ${arr(members)}) ON CONFLICT (id) DO NOTHING;`)
  out.push(`INSERT INTO sprints (id, project_id, name, goal, start_date, end_date, status) VALUES (${q(uuid(100 + p.n))}, ${q(uuid(p.n))}, 'Sprint 14', 'Vertical slice ready for playtest', '2026-11-09', '2026-11-22', 'active') ON CONFLICT (id) DO NOTHING;`)
  out.push(`INSERT INTO milestones (id, project_id, name, description, due_date, status) VALUES (${q(uuid(200 + p.n))}, ${q(uuid(p.n))}, 'Alpha', 'Feature-complete internal build', '2026-12-15', 'open') ON CONFLICT (id) DO NOTHING;`)
}

out.push('-- Board cards')
const statuses = ['backlog', 'todo', 'in_progress', 'in_review', 'done']
const priorities = ['low', 'medium', 'high']
let t = 0
for (const p of projects) {
  const people = byTeam(p.game)
  for (let i = 0; i < 8; i++) {
    const a = people[(i * 3 + p.n) % people.length]
    t++
    out.push(`INSERT INTO tasks (id, project_id, sprint_id, title, status, priority, assignee_id, creator_id, due_date, position) VALUES (${q(uuid(1000 + t))}, ${q(uuid(p.n))}, ${q(uuid(100 + p.n))}, ${q(`${p.name}: ${['Greybox the hub level', 'Rig the lead character', 'Tune combat feel', 'Audio pass on UI', 'Fix save-slot bug', 'Playtest feedback triage', 'Lighting pass', 'Localization hooks'][i]}`)}, ${q(statuses[(i + p.n) % statuses.length])}, ${q(priorities[i % 3])}, ${q(uid(a.id))}, ${q(uid(lead(p.game).id))}, ${q(`2026-11-${String(12 + i * 2).padStart(2, '0')}`)}, ${i}) ON CONFLICT (id) DO NOTHING;`)
  }
}

out.push('-- Meetings')
const meet = [['Studio standup', '2026-11-16', 10], ['Last Light playtest review', '2026-11-18', 14], ['Corebound alpha planning', '2026-11-19', 11]]
meet.forEach(([title, date, hour], i) => {
  out.push(`INSERT INTO meetings (id, organizer_id, title, description, date, start_hour, end_hour) VALUES (${q(uuid(2000 + i))}, ${q(uid('ceo'))}, ${q(title)}, 'Demo meeting', ${q(date)}, ${hour}, ${hour + 1}) ON CONFLICT (id) DO NOTHING;`)
  TEAM.slice(0, 6).forEach(m => out.push(`INSERT INTO meeting_invites (meeting_id, user_id, display_name, status) VALUES (${q(uuid(2000 + i))}, ${q(uid(m.id))}, ${q(m.name)}, 'accepted') ON CONFLICT (meeting_id, user_id) DO NOTHING;`))
})

out.push('COMMIT;')
writeFileSync(new URL('../supabase/seed.demo.sql', import.meta.url), out.join('\n') + '\n')
console.log(`wrote supabase/seed.demo.sql (${out.length} statements, ${TEAM.length} people)`)
